#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_maps_common_accents() {
        assert!(BASE.windows(2).all(|w| w[0].0 < w[1].0));
        for (accented, base) in [
            ('é', 'e'),
            ('É', 'E'),
            ('ö', 'o'),
            ('Å', 'A'),
            ('ñ', 'n'),
            ('ç', 'c'),
            ('ș', 's'),
            ('ệ', 'e'),
        ] {
            assert_eq!(base_letter(accented), base);
        }
        for unchanged in ['ø', 'æ', 'ł', 'ß', 'a', '東'] {
            assert_eq!(base_letter(unchanged), unchanged);
        }
    }
}
