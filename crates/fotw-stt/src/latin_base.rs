//! Base letters of precomposed Latin letters, for accent-insensitive matching.
//!
//! Generated from Unicode 15.0 canonical decompositions (Python `unicodedata`):
//! every character in U+00C0–U+024F and U+1E00–U+1EFF whose NFD is an ASCII
//! letter followed only by combining marks. Letters without a decomposition
//! (`ø`, `æ`, `ł`, `ß`) are unchanged, exactly as with NFD.

/// The ASCII base letter of a precomposed Latin letter, or the letter itself.
pub(crate) fn base_letter(c: char) -> char {
    if c.is_ascii() {
        return c;
    }
    BASE.binary_search_by_key(&c, |&(composed, _)| composed)
        .map_or(c, |i| BASE[i].1)
}

